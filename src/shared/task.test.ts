import { describe, expect, it } from "vitest";
import { updateTaskSchema, taskIdSchema, taskInputSchema } from "./task";

describe("task validation", () => {
  it.each([undefined, null, "", "   ", "\n\t", 123])("rejects an invalid title: %s", (title) => {
    expect(taskInputSchema.safeParse({ title }).success).toBe(false);
  });

  it("normalizes text fields", () => {
    expect(taskInputSchema.parse({ title: "  Estudar  ", description: "  tRPC  " })).toEqual({
      title: "Estudar", description: "tRPC",
    });
  });

  it.each([undefined, "", "   "])("accepts an optional description: %s", (description) => {
    expect(taskInputSchema.parse({ title: "Estudar", description }).description).toBeUndefined();
  });

  it("discards fields generated by the server", () => {
    expect(taskInputSchema.parse({ title: "Estudar", id: "forjado", createdAt: 0 })).toEqual({
      title: "Estudar",
    });
  });

  it("rejects an invalid ID", () => {
    expect(taskIdSchema.safeParse({ id: "inexistente" }).success).toBe(false);
  });

  it("requires a title and ID when updating", () => {
    expect(updateTaskSchema.safeParse({ title: "Estudar" }).success).toBe(false);
    expect(updateTaskSchema.safeParse({ id: "a3d08168-87a6-4b41-b488-96c8375ac2ee" }).success).toBe(false);
  });
});
